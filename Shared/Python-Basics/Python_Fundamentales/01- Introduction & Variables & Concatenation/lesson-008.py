# ---------------------------------
# -- Source Code and Translation --
# ---------------------------------

# Source Code:
# The original code written by the programmer.

# Translation:
# Converting source code into a form the computer can execute.

# Compilation:
# Translating the code before execution (Run Time).

# Run Time:
# The period when the program is running and executing commands.

# Interpreted:
# Code is translated/handled during execution.

# ---------------------------------
# Quick Summary
# ---------------------------------

